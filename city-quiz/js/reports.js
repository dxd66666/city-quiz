  function getReport(cityId) {
    for (var i = 0; i < CITY_REPORTS.length; i++) {
      if (CITY_REPORTS[i].id === cityId) return CITY_REPORTS[i];
    }
    throw new Error('未找到城市报告：' + cityId);
  }

  // 0-3 低 / 4-8 中 / 9-12 高
  function band(score) {
    if (score <= 3) return 'low';
    if (score <= 8) return 'mid';
    return 'high';
  }

  function subSentence(dim, score) {
    return SUB_SENTENCES[dim][band(score)];
  }

  function sceneSentence(dim, score) {
    return SCENE_SENTENCES[dim][band(score)];
  }

  // PART03：取 abs(score-6) 最大的两项，平局按 P,S,C,A,E,O,F,U 顺序
  function pickTopTwo(subScores) {
    var dims = SUB_ORDER.slice();
    dims.sort(function (a, b) {
      var da = Math.abs(subScores[a] - 6);
      var db = Math.abs(subScores[b] - 6);
      if (db !== da) return db - da; // 距离降序
      return SUB_ORDER.indexOf(a) - SUB_ORDER.indexOf(b); // 平局按固定顺序
    });
    return dims.slice(0, 2);
  }

  // 组装结果页所需的完整数据
  function buildReport(result) {
    var city = getReport(result.cityId);
    var subs = result.subScores;

    var dimensions = Object.keys(Q.DIM_GROUPS).map(function (key) {
      var g = Q.DIM_GROUPS[key];
      return {
        key: key,
        label: g.label,
        score: result.dimensions[key],
        subs: g.subs.map(function (d) {
          return { dim: d, name: Q.SUB_META[d].name, sentence: subSentence(d, subs[d]) };
        })
      };
    });

    var topTraits = pickTopTwo(subs).map(function (d) {
      return { dim: d, sentence: subSentence(d, subs[d]) };
    });

    var scenes = [
      { dim: 'U', sentence: sceneSentence('U', subs.U) },
      { dim: 'S', sentence: sceneSentence('S', subs.S) },
      { dim: 'E', sentence: sceneSentence('E', subs.E) }
    ];

    return {
      city: city,
      dimensions: dimensions,
      topTraits: topTraits,
      scenes: scenes,
      subScores: subs
    };
  }

